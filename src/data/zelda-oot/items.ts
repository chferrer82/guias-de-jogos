/** Mapa de nome e apelido para o item, usado pelos links automáticos. */
export const itemByName = new Map<string, Item>(
	items.flatMap((it) => [it.name, ...(it.aliases ?? [])].map((n) => [n, it] as const)),
);

/** Acha o item de um texto como "Bumerangue (Boomerang)"; ignora o nome em inglês entre parênteses. */
export const findItem = (text: string): Item | undefined =>
	itemByName.get(text.replace(/\s*\([^)]*\)\s*$/, '').trim());
